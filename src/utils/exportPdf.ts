/**
 * 创建邮件分享链接
 */
export function createEmailShareLink(
  subject: string = 'AgentForge Dashboard Report',
  body: string = ''
): string {
  const encodedSubject = encodeURIComponent(subject)
  const encodedBody = encodeURIComponent(
    body ||
    `Hi,\n\n` +
    `Please find the attached AgentForge Dashboard Report.\n\n` +
    `Generated at: ${new Date().toLocaleString()}\n` +
    `Powered by AgentForge v2.4.0\n\n` +
    `Best regards`
  )

  return `mailto:?subject=${encodedSubject}&body=${encodedBody}`
}

/**
 * 导出数据为CSV
 */
export function exportDataToCsv(
  data: any[],
  filename: string = 'data'
): void {
  if (!data || data.length === 0) {
    showErrorToast('没有数据可导出')
    return
  }

  try {
    // 获取所有键作为表头
    const headers = Object.keys(data[0])

    // 创建CSV内容
    const csvContent = [
      headers.join(','), // 表头
      ...data.map(row =>
        headers.map(header => {
          const value = row[header]
          // 处理包含逗号的值
          return typeof value === 'string' && value.includes(',')
            ? `"${value}"`
            : value
        }).join(',')
      )
    ].join('\n')

    // 创建Blob并下载
    const blob = new Blob(['\ufeff' + csvContent], {
      type: 'text/csv;charset=utf-8;'
    })
    const url = URL.createObjectURL(blob)
    const link = document.createElement('a')
    link.href = url
    link.download = `${filename}-${Date.now()}.csv`
    link.click()
    URL.revokeObjectURL(url)

    showSuccessToast('CSV导出成功！')
  } catch (error) {
    console.error('CSV export failed:', error)
    showErrorToast('CSV导出失败')
  }
}

/**
 * 导出数据为JSON
 */
export function exportDataToJson(
  data: any,
  filename: string = 'data'
): void {
  try {
    const jsonContent = JSON.stringify(data, null, 2)
    const blob = new Blob([jsonContent], { type: 'application/json' })
    const url = URL.createObjectURL(blob)
    const link = document.createElement('a')
    link.href = url
    link.download = `${filename}-${Date.now()}.json`
    link.click()
    URL.revokeObjectURL(url)

    showSuccessToast('JSON导出成功！')
  } catch (error) {
    console.error('JSON export failed:', error)
    showErrorToast('JSON导出失败')
  }
}

export default {
  exportDashboardToPdf,
  exportChartToPdf,
  exportMultiPagePdf,
  createEmailShareLink,
  exportDataToCsv,
  exportDataToJson
}
